-- Schema of the SDLC orchestrator control plane (H2 2.x; portable SQL).
--
-- runs:         one row per run; the whole aggregate is stored as one JSON document (snapshot_json) next to a few
--               queryable columns; version is the JPA optimistic-lock version.
-- audit_events: append-only audit trail, one row per engine event, ordered by (run_id, seq).
-- artifacts:    every artifact version a stage produced (also contained in the snapshot), queryable per run.
--
-- Large JSON columns are unbounded VARCHAR (TEXT semantics on PostgreSQL). TEXT/CLOB are deliberately not used:
-- H2 maps TEXT to CLOB, which Hibernate schema validation rejects for a plain String attribute, while unbounded
-- VARCHAR validates (spring.jpa.hibernate.ddl-auto=validate) and needs no @Lob streaming.
-- No CHECK (x IN (...)) constraints: H2 2.4 binds such constraints to the session that created them (the Flyway
-- connection), which breaks later inserts. Enum domains are enforced by the application.

CREATE TABLE runs (
    id            VARCHAR(64)   NOT NULL PRIMARY KEY,
    scenario      VARCHAR(64)   NOT NULL,
    status        VARCHAR(32)   NOT NULL,
    halt_reason   VARCHAR(64),
    requirement   VARCHAR(4000) NOT NULL,
    plan_version  INT           NOT NULL,
    created_at    TIMESTAMP     NOT NULL,
    updated_at    TIMESTAMP     NOT NULL,
    ended_at      TIMESTAMP,
    snapshot_json VARCHAR       NOT NULL,
    version       BIGINT        NOT NULL
);

CREATE INDEX idx_runs_created ON runs (created_at);

CREATE TABLE audit_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id     VARCHAR(64)   NOT NULL,
    seq        BIGINT        NOT NULL,
    ts         TIMESTAMP     NOT NULL,
    stage_id   VARCHAR(64),
    type       VARCHAR(64)   NOT NULL,
    actor_type VARCHAR(16)   NOT NULL,
    actor_id   VARCHAR(128)  NOT NULL,
    message    VARCHAR(2000) NOT NULL,
    data_json  VARCHAR,
    CONSTRAINT uk_audit_events_run_seq UNIQUE (run_id, seq)
);

CREATE INDEX idx_audit_events_run ON audit_events (run_id);

CREATE TABLE artifacts (
    id              VARCHAR(64) NOT NULL PRIMARY KEY,
    run_id          VARCHAR(64) NOT NULL,
    stage_id        VARCHAR(64) NOT NULL,
    kind            VARCHAR(64) NOT NULL,
    version         INT         NOT NULL,
    plan_version    INT         NOT NULL,
    hash            VARCHAR(64) NOT NULL,
    payload_json    VARCHAR     NOT NULL,
    provenance_json VARCHAR     NOT NULL,
    created_at      TIMESTAMP   NOT NULL,
    CONSTRAINT uk_artifacts_run_stage_version UNIQUE (run_id, stage_id, version)
);

CREATE INDEX idx_artifacts_run ON artifacts (run_id);
