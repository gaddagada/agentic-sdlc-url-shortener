-- Initial schema of the URL shortener.
-- Portable between H2 2.x and PostgreSQL 17: identity columns, TIMESTAMP (UTC wall-clock, no time zone),
-- VARCHAR, BOOLEAN. Hibernate validates this schema at startup (spring.jpa.hibernate.ddl-auto=validate).
--
-- links.status deliberately has no CHECK (status IN (...)) constraint: H2 2.4 binds a constant IN-list in a check
-- constraint to the session that created it, and every later insert fails with "The database has been closed"
-- once that (Flyway) connection is closed. The status domain is enforced by the JPA enum mapping instead.

CREATE TABLE links (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(32)   NOT NULL,
    original_url VARCHAR(2048) NOT NULL,
    status       VARCHAR(16)   NOT NULL,
    created_at   TIMESTAMP     NOT NULL,
    expires_at   TIMESTAMP,
    click_count  BIGINT        NOT NULL DEFAULT 0,
    custom_alias BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_links_code UNIQUE (code)
);

CREATE TABLE click_events (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_id           BIGINT       NOT NULL,
    occurred_at       TIMESTAMP    NOT NULL,
    referrer_host     VARCHAR(255),
    user_agent_family VARCHAR(32)  NOT NULL,
    ip_hash           VARCHAR(64)  NOT NULL,
    CONSTRAINT fk_click_events_link FOREIGN KEY (link_id) REFERENCES links (id)
);

CREATE INDEX idx_click_events_link_time ON click_events (link_id, occurred_at);
-- Retention purge (ClickRetentionJob) deletes by occurred_at alone, which the (link_id, occurred_at) index cannot serve.
CREATE INDEX idx_click_events_occurred_at ON click_events (occurred_at);

-- body is an unbounded VARCHAR (TEXT semantics on PostgreSQL). TEXT itself is not used because H2 maps it to CLOB,
-- which Hibernate's schema validation does not accept for a String attribute on H2, while CLOB/@Lob maps to OID
-- on PostgreSQL. Unbounded VARCHAR validates on both databases.
CREATE TABLE idempotency_records (
    idem_key    VARCHAR(128) PRIMARY KEY,
    fingerprint VARCHAR(64)  NOT NULL,
    status      INT          NOT NULL,
    body        VARCHAR      NOT NULL,
    created_at  TIMESTAMP    NOT NULL
);

CREATE INDEX idx_idempotency_records_created ON idempotency_records (created_at);
